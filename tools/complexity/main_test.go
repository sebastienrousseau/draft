func TestHalsteadDifficulty(t *testing.T) {
	// Operators: func ( { return + (5); operands f a int int a 1 (6 in
	// total, 4 distinct). Closing brackets and inserted newlines are not
	// counted. (5/2) * (6/4) = 3.75.
	if got := halsteadDifficulty([]byte("func f(a int) int {\n\treturn a + 1\n}")); got != 3.75 {
		t.Errorf("halsteadDifficulty = %v, want 3.75", got)
	}
	if got := halsteadDifficulty([]byte("{}")); got != 0 {
		t.Errorf("no operands should be 0, got %v", got)
	}
}

func TestFuncName(t *testing.T) {
	src := `package p
func F() {}
func (T) A() {}
func (t *T) B() {}
func (g G[K]) C() {}
func (g *H[K, V]) D() {}
func (x [2]int) E() {}
`
	f, err := parser.ParseFile(token.NewFileSet(), "p.go", src, parser.AllErrors)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, d := range f.Decls {
		got = append(got, funcName(d.(*ast.FuncDecl)))
	}
	want := "F T.A T.B G.C H.D ?.E"
	if strings.Join(got, " ") != want {
		t.Errorf("funcName = %v, want %s", got, want)
	}
}

// tree writes a small module: one function over the cyclomatic ceiling, plus
// a test file, a generated file and a testdata file that must be ignored.
func tree(t *testing.T, branches int) string {
	t.Helper()
	dir := t.TempDir()
	write(t, dir, "a/a.go", "package a\n\n"+busy("Busy", branches)+"\nfunc Small() {}\n")
	write(t, dir, "a/a_test.go", "package a\n\n"+busy("TestBusy", 30))
	write(t, dir, "a/gen.go", "// Code generated by hand. DO NOT EDIT.\n\npackage a\n\n"+busy("Gen", 30))
	write(t, dir, "a/testdata/x.go", "package x\n\n"+busy("Fixture", 30))
	write(t, dir, ".hidden/h.go", "package h\n\n"+busy("Hidden", 30))
	return dir
}

func busy(name string, branches int) string {
	var b strings.Builder
	b.WriteString("func " + name + "(x int) int {\n")
	for i := 0; i < branches; i++ {
		b.WriteString("\tif x == 1 {\n\t\tx++\n\t}\n")
	}
	b.WriteString("\treturn x\n}\n")
	return b.String()
}

func write(t *testing.T, dir, rel, body string) {
	t.Helper()
	p := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestMeasureSkipsTestsGeneratedAndFixtures(t *testing.T) {
	m, err := measure(tree(t, 12))
	if err != nil {
		t.Fatal(err)
	}
	if got := sortedKeys(m); strings.Join(got, ",") != "a/a.go (file),a/a.go Busy,a/a.go Small" {
		t.Fatalf("measured units = %v", got)
	}
	if m["a/a.go Busy"][cyclomatic] != 13 || m["a/a.go Busy"][lines] != 39 {
		t.Errorf("Busy = %v", m["a/a.go Busy"])
	}
}

func TestMeasureReportsParseErrors(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "bad.go", "package\n")
	if _, err := measure(dir); err == nil {
		t.Error("want a parse error")
	}
	if _, err := measure(filepath.Join(dir, "missing")); err == nil {
		t.Error("want a walk error")
	}
}

// gate runs the command against dir and returns its exit code and output.
func gate(t *testing.T, dir string, extra ...string) (int, string) {
	t.Helper()
	var out, errs bytes.Buffer
	args := append([]string{"-root", dir, "-baseline", filepath.Join(dir, "baseline.txt")}, extra...)
	code := run(args, &out, &errs)
	return code, out.String() + errs.String()
}

func TestGateLifecycle(t *testing.T) {
	dir := tree(t, 12)
	if code, out := gate(t, dir); code != 1 || !strings.Contains(out, "a/a.go Busy: cyclomatic 13 is over 10") {
		t.Fatalf("a new offender must fail: %d %q", code, out)
	}
	if code, out := gate(t, dir, "-write"); code != 0 || !strings.Contains(out, "wrote 1 offender") {
		t.Fatalf("first write: %d %q", code, out)
	}
	if code, out := gate(t, dir); code != 0 {
		t.Fatalf("recorded offender must pass: %d %q", code, out)
	}

	write(t, dir, "a/a.go", "package a\n\n"+busy("Busy", 14))
	if code, out := gate(t, dir); code != 1 || !strings.Contains(out, "cyclomatic 15 is over 13") {
		t.Fatalf("a worse offender must fail: %d %q", code, out)
	}
	if code, out := gate(t, dir, "-write"); code != 1 || !strings.Contains(out, "not rewriting") {
		t.Fatalf("-write must refuse a regression: %d %q", code, out)
	}

	write(t, dir, "a/a.go", "package a\n\n"+busy("Busy", 11))
	if code, out := gate(t, dir); code != 1 || !strings.Contains(out, "cyclomatic improved from 13 to 12") {
		t.Fatalf("an unrecorded improvement must fail: %d %q", code, out)
	}
	gate(t, dir, "-write")
	data, _ := os.ReadFile(filepath.Join(dir, "baseline.txt"))
	if !strings.Contains(string(data), "a/a.go Busy cyclomatic=12 ") {
		t.Fatalf("baseline after improvement:\n%s", data)
	}

	write(t, dir, "a/a.go", "package a\n\nfunc Small() {}\n")
	if code, out := gate(t, dir); code != 1 || !strings.Contains(out, "improved from 12 to 0") {
		t.Fatalf("a removed offender must be written out: %d %q", code, out)
	}
	gate(t, dir, "-write")
	if code, out := gate(t, dir); code != 0 || !strings.Contains(out, "no function or file is worse") {
		t.Fatalf("empty baseline must pass: %d %q", code, out)
	}
}

func TestGateErrors(t *testing.T) {
	dir := tree(t, 1)
	if code, _ := gate(t, dir, "-nope"); code != 2 {
		t.Errorf("bad flag: %d", code)
	}
	write(t, dir, "baseline.txt", "a/a.go Busy\n")
	if code, out := gate(t, dir); code != 2 || !strings.Contains(out, "line 1") {
		t.Errorf("short line: %d %q", code, out)
	}
	write(t, dir, "baseline.txt", "# c\n\na/a.go Busy speed=1\n")
	if code, out := gate(t, dir); code != 2 || !strings.Contains(out, "line 3: bad metric") {
		t.Errorf("unknown metric: %d %q", code, out)
	}
	write(t, dir, "baseline.txt", "a/a.go Busy lines=x\n")
	if code, out := gate(t, dir); code != 2 || !strings.Contains(out, "bad value") {
		t.Errorf("bad value: %d %q", code, out)
	}
	if err := os.Mkdir(filepath.Join(dir, "dir.txt"), 0o755); err != nil {
		t.Fatal(err)
	}
	var out, errs bytes.Buffer
	if code := run([]string{"-root", dir, "-baseline", filepath.Join(dir, "dir.txt")}, &out, &errs); code != 2 {
		t.Errorf("unreadable baseline: %d %q", code, errs.String())
	}
	if code := run([]string{"-root", filepath.Join(dir, "missing")}, &out, &errs); code != 2 {
		t.Errorf("missing root: %d", code)
	}
	if code := run([]string{"-root", dir, "-baseline", filepath.Join(dir, "no", "such", "b.txt"), "-write"}, &out, &errs); code != 2 {
		t.Errorf("unwritable baseline: %d", code)
	}
}
